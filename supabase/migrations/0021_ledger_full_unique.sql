-- ═══════════════════════════════════════════════════════════════════
-- 원장 전체 유니크 — 0018 의 사각지대(만료 행)를 덮는다
--
-- ── 무엇이 새어 나갔는가 ──────────────────────────────────────────
-- 0018 의 `*_one_open` 인덱스는 `where effective_to is null` 이라 **열린 행만**
-- 본다. 만료 행은 몇 벌이 쌓여도 막히지 않았고, 실제로 그렇게 됐다:
--
--   122 * (2026-02-24 ~ 2026-07-24, 10%)  ← 2026-07-30 04:19 시드
--   122 * (2026-02-24 ~ 2026-07-24, 10%)  ← 2026-07-30 04:30 시드 (동일 행)
--
-- 특별한 일이 있었던 게 아니다. **시드를 두 번 돌린 것만으로** 생겼다.
-- 아카이브 불변 규칙이 들어간 뒤 로더가 만료 행을 못 지우게 됐는데, 시드는
-- 여전히 재적재를 시도해서 중복이 남은 것이다. 지금은 시드도 만료 행을 건너뛰지만
-- 그건 스크립트 계층이고, 스크립트는 다음번에 또 새로 생긴다.
--
-- ── 왜 위생 문제가 아니라 정확성 장치인가 ─────────────────────────
-- 앱에 "Rates as-of date" 입력이 있다. 기준일을 2026-02-24~07-24 로 잡으면 두 행이
-- 모두 매칭된다. 합산되면 10% 가 아니라 20% 다.
--
-- 실측했다 (tests/duplicate-ledger.test.ts): **합산되지 않는다.**
-- resolvePrograms 가 program_code 를 키로 Map 에 하나만 담는다. 이번 중복은
-- 두 행의 세율이 같아서 결과도 같았다.
--
-- 진짜 위험은 거기가 아니다 — 키가 program_code 라 **어느 행이 이기는가가 조용히
-- 결정된다.** 세율이 다른 중복이 들어오면 배열 순서로 답이 갈리고, PostgREST 는
-- ORDER BY 없이 순서를 보장하지 않는다. 낮은 쪽이 이기면 관세 과소계상이다 —
-- 오차 비대칭 원칙상 가장 나쁜 방향이고, 조용하다.
--
-- 엔진을 "높은 쪽이 이긴다" 로 고치는 선택지도 있지만 그건 틀린 데이터를 그럴듯하게
-- 만드는 것이다. DB 가 애초에 거부하는 쪽이 맞다.
--
-- ── 이 마이그레이션 자체가 정리 완료 검사다 ───────────────────────
-- 중복이 하나라도 남아 있으면 인덱스 생성이 실패한다. 통과했다는 것은 원장에
-- 중복이 없다는 뜻이다. 별도 확인 절차가 필요 없다.
-- ═══════════════════════════════════════════════════════════════════

-- nulls not distinct 가 핵심이다. origin_country(전 원산지)와 effective_to(열린 행)
-- 둘 다 null 이 될 수 있는데, 기본 동작은 null 끼리 서로 다르다고 보아 중복을
-- 그대로 허용한다 — 즉 **가장 흔한 두 경우가 정확히 안 막힌다.**
create unique index if not exists rate_ledger_no_duplicates
  on public.rate_ledger (program_code, hts_code, origin_country, effective_from, effective_to)
  nulls not distinct;

comment on index public.rate_ledger_no_duplicates is
  '같은 (프로그램, HTS, 원산지, 발효구간) 행은 하나. 0018 의 one_open 은 열린 행만 '
  '보아 만료 행 중복을 놓쳤고, 시드를 두 번 돌린 것만으로 122 만료 행이 두 벌이 됐다. '
  '세율이 다른 중복이 들어오면 어느 행이 이길지 배열 순서로 갈려 과소계상이 될 수 있다.';

-- program_exclusions 도 같은 사각지대를 갖는다. 면제는 세율을 0 으로 만들므로
-- 중복이 조용히 쌓이면 더 위험하다.
create unique index if not exists program_exclusions_no_duplicates
  on public.program_exclusions (program_code, hts_code, effective_from, effective_to)
  nulls not distinct;
